    cur = st.session_state.get("lang_code", "en")
    if cur not in codes:
        cur = "en"

    def _fmt(c):
        v = LANGS[c] if isinstance(LANGS, dict) else c
        return v if isinstance(v, str) else c

    wkey = f"_lang_widget_{page_key}"

    def _save():
        st.session_state["lang_code"] = st.session_state[wkey]

    st.selectbox(label, codes, index=codes.index(cur), format_func=_fmt, key=wkey, on_change=_save)
    return st.session_state.get("lang_code", cur)